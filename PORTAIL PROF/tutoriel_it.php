    <h2>SCHERMATA 5</h2>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image29.png" alt="Controllo dei documenti caricati">
    </div>

    <p>In questa fase del processo, puoi ancora tornare indietro per modificare la tua dichiarazione.</p>

    <p>Prima dell’invio finale, ricordati di controllare:</p>

    <ul>
      <li>che tutti i tuoi corsi del mese siano stati inseriti,</li>
      <li>che gli orari siano corretti,</li>
      <li>che le informazioni complementari siano state salvate, se necessario,</li>
      <li>e che tutti i giustificativi richiesti siano stati caricati.</li>
    </ul>

    <p>Una volta inviata la dichiarazione, il tuo mese di aprile viene trasmesso all’amministrazione.</p>

    <p class="danger">MA ATTENZIONE:</p>

    <p>Se clicchi sul pulsante “CONFERMO LA MIA DICHIARAZIONE”, non potrai più tornare sulla tua dichiarazione per questo mese. Quando proverai a collegarti al tuo portale, l’accesso sarà chiuso per il mese della tua dichiarazione.</p>

