    <h2>SCHERMATA 2</h2>

    <h3>Aggiungere informazioni complementari</h3>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image10.png" alt="Informazioni complementari">
    </div>

    <p>Questa schermata è dedicata a tutte le informazioni che ritieni utili comunicarci su ogni corso / allievo.</p>

    <p>3 sezioni:</p>

    <ol style="font-size:18px; margin-left:22px;">
      <li style="margin:8px 0;">Assenze. Esempio: un allievo che è assente troppo spesso. Devi indicare il numero di ore di assenza non giustificate nel mese.</li>
      <li style="margin:8px 0;">Osservazioni pedagogiche: informazioni didattiche riguardanti i progressi dell’allievo.</li>
      <li style="margin:8px 0;">Problemi: un allievo che non riesci a contattare per fissare una lezione, oppure qualsiasi altro problema che incontri con un allievo.</li>
    </ol>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image11.png" alt="Inserimento delle informazioni complementari">
    </div>

    <p>Nella sezione “Informazioni supplementari”, scegli il corso interessato e poi compila, se necessario:</p>

    <ul>
      <li>le ore di assenza dell’allievo per questo corso,</li>
      <li>le osservazioni pedagogiche,</li>
      <li>le informazioni o i problemi riguardanti il corso o l’allievo.</li>
    </ul>

    <p>Poi clicca su</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image12.png" alt="Salva le tue informazioni">
    </div>

    <p>Attenzione: se non salvi prima di selezionare un altro corso, le tue note e i tuoi commenti non verranno salvati.</p>

    <p>Puoi fare la stessa cosa anche per gli altri corsi del mese.</p>

    <p>In fondo alla pagina, puoi anche aggiungere suggerimenti generali se necessario. Per esempio, se hai bisogno di un libro, di un documento, ecc.</p>

    <p>Se hai dimenticato un corso, puoi tornare alla schermata precedente cliccando su:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image13.png" alt="Torna alle lezioni">
    </div>

    <p>Quando queste operazioni sono terminate, clicca in basso a destra su:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image14.png" alt="Avanti riepilogo e caricamenti">
    </div>

    <h2>SCHERMATA 3</h2>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image15.png" alt="Riepilogo degli inserimenti">
    </div>

    <p>Controlla il riepilogo dei corsi che hai inserito nella Schermata 1.</p>

    <p>Nella pagina Riepilogo degli inserimenti, controlla attentamente:</p>

    <ul>
      <li>il numero totale di ore del mese,</li>
      <li>le ore per ogni corso,</li>
      <li>la data,</li>
      <li>l’orario,</li>
      <li>la modalità (in presenza o online). Devi selezionarla nella tabella.</li>
      <li>i chilometri, se ce ne sono,</li>
      <li>e tutte le righe inserite.</li>
    </ul>

    <p>In questa fase puoi ancora correggere direttamente la data di un corso, l’ora di inizio e di fine, oppure eliminare una riga se necessario. Ti viene anche richiesto di indicare se il corso è stato svolto in presenza o online. Puoi fare queste correzioni direttamente nella tabella.</p>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image16.png" alt="Modifica del riepilogo">
    </div>

    <p>Se hai dimenticato un corso, non puoi aggiungerlo qui. Devi tornare alla Schermata 1.</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image17.png" alt="Modifica i miei corsi">
    </div>

    <p>Attenzione: se modifichi qualcosa nella tabella, apparirà un banner giallo che ti chiederà di salvare la modifica.</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image18.png" alt="Salva le tue modifiche">
    </div>

    <p>Se non salvi, le tue correzioni non saranno prese in considerazione.</p>

    <p>Quando hai controllato tutto e la tua dichiarazione corrisponde esattamente ai tuoi fogli presenze cartacei, clicca su:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image19.png" alt="Avanti ai miei giustificativi">
    </div>

    <h2>SCHERMATA 4</h2>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image20.png" alt="Inviare i giustificativi del mese">
    </div>

    <p>Questa schermata è una fase essenziale del processo della tua dichiarazione.</p>

    <p>In questa pagina selezionerai i file che vuoi inviarci, cioè i giustificativi che confermano la tua dichiarazione.</p>

    <p>1/ Leggi attentamente le istruzioni.</p>

    <p>Regola semplice:</p>

    <ul>
      <li>se sei dipendente: devi inviare il file chiamato PRESENCE,</li>
      <li>se sei lavoratore autonomo: devi inviare il file chiamato PRESENCE e il file chiamato FACTURE.</li>
    </ul>

    <p>Questi sono i file obbligatori che hai rinominato sul tuo PC prima di collegarti.</p>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image21.png" alt="Istruzioni per l'invio dei giustificativi">
    </div>

    <p>2/ In fondo alla pagina, cerca il pulsante:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image22.png" alt="Seleziona file">
    </div>

    <p>Sotto, puoi vedere un banner giallo e il pulsante:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image23.png" alt="Uploader disattivato">
    </div>

    <p>Per il momento, questo pulsante è grigio e inattivo.</p>

    <p>3/ Cliccaci sopra. Si apre l’esplora file del tuo PC. Cerca i file Presence.pdf e facture.pdf se sei un lavoratore autonomo.</p>

    <p>Attendi qualche secondo e vedrai i nomi dei tuoi file accanto al pulsante Select.</p>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image24.png" alt="File selezionati">
    </div>

    <p>Vedrai anche che il pulsante è diventato blu. Ora è attivo. Puoi cliccare su</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image25.png" alt="Uploader attivo">
    </div>

    <p><strong>I tuoi file saranno inviati ad Audra Langues.</strong></p>

    <p>Se il pulsante non diventa blu, significa che hai selezionato i file sbagliati. Il software è progettato per rilevare le parole presence e facture nei nomi dei file.</p>

    <p>Puoi selezionare anche altri file se vuoi (coordinate bancarie, documenti, relazioni pedagogiche, ecc.).</p>

    <p>Per i fogli presenze, puoi caricare diversi file di presenza se hai scansionato i fogli separatamente. In questo caso, ti consiglio di nominare i tuoi file così: “presence_cours 21526.pdf”, “presence_cours19884.pdf”, ecc.</p>

    <p>In linea di principio, puoi allegare file Word o Excel. Non ti consiglio di allegare file immagine o foto perché sono molto pesanti da caricare e potresti superare il limite fissato a 20 MB.</p>

    <p>Dopo aver cliccato sul pulsante Uploader,</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image26.png" alt="Uploader pronto">
    </div>

    <p>4/ La pagina cambia e passi a: SCHERMATA 5</p>

    <div class="img">
      <img src="/modules/portail_prof/tutoriel_img/image27.png" alt="Schermata 5">
    </div>

    <p>Nella tabella centrale vedrai i tuoi file. Il software ha dato loro un nuovo nome: PRESENCE_PRESENCE_20260409…. È normale. Se clicchi sul pulsante “View”, potrai verificare che si tratta effettivamente del file dei tuoi fogli presenze. Se hai sbagliato nella scelta del file, clicca sull’icona del cestino e ricomincia: Select files.</p>

    <p>5/ Poi clicca sul pulsante “Vai alla fase successiva”:</p>

    <div class="img img-noborder">
      <img src="/modules/portail_prof/tutoriel_img/image28.png" alt="Vai alla fase successiva">
